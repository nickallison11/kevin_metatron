/// The country's name and code, from either one ("ZA" or "South Africa").
pub fn resolve(country: &str) -> Option<(&'static str, &'static str)> {
    let c = country.trim();
    COUNTRIES
        .iter()
        .find(|(code, name)| code.eq_ignore_ascii_case(c) || name.eq_ignore_ascii_case(c))
        .map(|(code, name)| (*code, *name))
}

/// A case-insensitive Postgres regex for the region words that cover this
/// country code ("Pan-African", "EMEA"...), if any.
pub fn region_pattern(code: &str) -> Option<String> {
    let words: Vec<&str> = REGIONS
        .iter()
        .filter(|(_, codes)| codes.split(' ').any(|c| c == code))
        .map(|(words, _)| *words)
        .collect();
    (!words.is_empty()).then(|| words.join("|"))
}
